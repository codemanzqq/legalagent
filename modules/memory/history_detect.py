"""
判断用户是否在询问「与自己过往聊天记录相关」的问题。

供 RagPipeline 优先路由：命中则仅从库内最近若干轮问答生成回复（不经向量检索）。
"""

from __future__ import annotations

import re

# 正则数组：语义覆盖「数量统计」「前/最后 N 条」「聊天记录」「我之前问过」等口语。
# 宁可少量误判为自述历史（走记忆分支），也不要漏判导致无法列举「问过什么」。
_HISTORY_PATTERNS: tuple[re.Pattern[str], ...] = (
    # 我问过 / 问了几个 / 一共几个（偏统计类）
    re.compile(r"我一共问|总共问|一共问|问过几个|问了几个|几个问题"),
    # 「前 8 个问题」「前三个问」等序数表达
    re.compile(r"前\s*\d+\s*个\s*(问题|问)"),
    # 「第 3 个问」等
    re.compile(r"第\s*\d+\s*个\s*(问题|问)"),
    # 「最后 5 个问」「最后几个问题」「我最后问的」含口语误「我最后问题的」
    re.compile(r"最后\s*\d*\s*个\s*(问题|问)|最后\s*(几|多少)\s*(个\s*)?(问题|问)"),
    re.compile(r"我最后"),
    # 「的 5 个问题是什么」类（如「我最后问题的5个问题是什么」）
    re.compile(r"的\s*\d+\s*个\s*问题"),
    # 历史、聊天、记录等显性关键词
    re.compile(r"历史\s*(问题|记录|聊天)|聊天记录|聊天历史"),
    # 时间/顺序副词 + 问/说（含「最后」已由上文覆盖时可辅助）
    re.compile(r"我(之前|刚才|前面|上次|早前)(问|提到|说过)"),
    # 「我问过什么」
    re.compile(r"我\s*问\s*过\s*(什么|啥)"),
    # 「上次问」「上回问」
    re.compile(r"上次\s*问|上回\s*问"),
    # 「回顾我」「统计我问」等松散说法（.{0,6} 限制跨度防误伤）
    re.compile(r"(回顾|汇总|统计).{0,6}(我|问|聊)"),
    # 「哪些问题」「问过哪些」（偏列举，易与自述历史混淆故收口为含「我」或上下文联结）
    re.compile(r"(我|咱|俺).{0,4}(哪些|哪几)(个\s*)?(问题|问)"),
)


def is_self_history_question(text: str) -> bool:
    """
    命中「统计/列举/回顾自身聊天记录」类口语时返回 True；RagPipeline 据此走库内记忆专用分支。
    """
    s = text.strip()
    if len(s) < 2:
        return False
    return any(p.search(s) for p in _HISTORY_PATTERNS)
